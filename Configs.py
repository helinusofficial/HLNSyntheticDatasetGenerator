    def _build_config_text(self) -> str:
        lines = []

        lines.append("")
        lines.append("=" * 90)
        lines.append("SyntheticDatasetConfig Configuration")
        lines.append("=" * 90)

        lines.append("")
        lines.append("[MODEL]")
        lines.append(f"Model_Path                : {self.model_path}")
        lines.append(f"N_CTX                     : {self.n_ctx}")
        lines.append(f"N_Threads                 : {self.n_threads}")
        lines.append(f"N_Batch                   : {self.n_batch}")
        lines.append(f"N_GPU_Layers              : {self.n_gpu_layers}")
        lines.append(f"verbose                   : {self.verbose}")
        lines.append(f"Show_Generated_Output     : {self.Show_Generated_Output}")

        lines.append("")
        lines.append("[DATASET]")
        lines.append(f"Num_Conversations         : {self.num_conversations}")
        lines.append(f"Output_File               : {self.output_file}")
        lines.append(f"save_interval             : {self.save_interval}")

        lines.append("")
        lines.append("[GENERATION]")
        lines.append(f"Max_Turns                 : {self.max_turns}")
        lines.append(f"Max_Tokens                : {self.max_tokens}")
        lines.append(f"Temperature               : {self.temperature}")

        lines.append("")
        lines.append("[TOPICS]")
        lines.append(f"Topics_Count              : {len(self.topics)}")
        lines.append(f"Topics                    : {self.topics}")

        lines.append("")
        lines.append("[SYSTEM PROMPT]")
        lines.append(self.system_prompt)

        lines.append("")
        lines.append("[CONVERSATION PROMPT]")
        lines.append(self.conversation_prompt)

        lines.append("-" * 113)

        text = "\n".join(lines)

        text = re.sub(
            r"\\u([0-9a-fA-F]{4})",
            lambda m: chr(int(m.group(1), 16)),
            text
        )

        return text

